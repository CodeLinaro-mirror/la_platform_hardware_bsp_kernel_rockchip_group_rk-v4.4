static int i2c_write_bytes(struct i2c_client *client, uint8_t *data, uint16_t len)
{
	struct i2c_msg msg;
	int ret = -1;
	int retry = 3;

	msg.flags = 0;
	msg.addr = client->addr;
	msg.len = len;
	msg.buf = data;
	do
	{
		ret = i2c_transfer(client->adapter, &msg, 1);
		retry--;
		if(ret < 0)
		{
			mdelay(30);
			pr_info("####val = [0: %0x][1: %0x][2: %0x] retry =%d\n", data[0],data[1],data[2], retry);
		}
	} while((ret < 0) && (retry > 0));

	return ret;
}

