static unsigned int alg_index = 0;
static int npca110_alg_get(struct snd_kcontrol *kcontrol,
		struct snd_ctl_elem_value *ucontrol)
{
	struct soc_enum *e = (struct soc_enum *)kcontrol->private_value;
	unsigned int val, bitmask;

	for (bitmask = 1; bitmask < e->items; bitmask <<= 1)
		;
	val = alg_index;
	ucontrol->value.enumerated.item[0]
		= (val >> e->shift_l) & (bitmask - 1);
	if (e->shift_l != e->shift_r)
		ucontrol->value.enumerated.item[1] =
			(val >> e->shift_r) & (bitmask - 1);

	return 0;
}

static int npca110_alg_put(struct snd_kcontrol *kcontrol,
		struct snd_ctl_elem_value *ucontrol)
{
	struct snd_soc_codec *codec = snd_kcontrol_chip(kcontrol);
	struct npca110_priv *npca110 = snd_soc_codec_get_drvdata(codec);
	struct soc_enum *e = (struct soc_enum *)kcontrol->private_value;
	unsigned int val;
	unsigned int mask, bitmask;

	if (npca110 == NULL)
		pr_info("%s npca110 is NULL\n",__func__);

	for (bitmask = 1; bitmask < e->items; bitmask <<= 1)
		;
	if (ucontrol->value.enumerated.item[0] > e->items - 1)
		return -EINVAL;
	val = ucontrol->value.enumerated.item[0] << e->shift_l;
	mask = (bitmask - 1) << e->shift_l;
	if (e->shift_l != e->shift_r) {
		if (ucontrol->value.enumerated.item[1] > e->items - 1)
			return -EINVAL;
		val |= ucontrol->value.enumerated.item[1] << e->shift_r;
		mask |= (bitmask - 1) << e->shift_r;
	}
	alg_index = val;

	switch(val) {
		case 0:
			MaxxDSP_SendCmd (MaxxAudio_Cmd_Standard_Alg, sizeof(MaxxAudio_Cmd_Standard_Alg), npca110->npca110_i2c);
			break;
		case 1:
			MaxxDSP_SendCmd (MaxxAudio_Cmd_Resounding_Alg, sizeof(MaxxAudio_Cmd_Resounding_Alg), npca110->npca110_i2c);
			break;
		case 2:
			MaxxDSP_SendCmd (MaxxAudio_Cmd_Relaxing_Alg, sizeof(MaxxAudio_Cmd_Relaxing_Alg), npca110->npca110_i2c);
			break;
		default:
			pr_info("%s Not Support other's Algorithm\n",__func__);
			return 0;
	}
	pr_info("%s Algorithm=%s\n",__func__, e->texts[alg_index]);
	return 1;
}

