static int npca110_i2c_probe(struct i2c_client *i2c,
		const struct i2c_device_id *id)
{
	struct npca110_priv *npca110;
	struct device_node *np = i2c->dev.of_node;
	enum of_gpio_flags flags;
	int npca110_reset_gpio;
	int linein_irq;
	int ret;
	pr_info("### %s,%d\n",__func__,__LINE__);
	pr_debug("### %s,%d\n",__func__,__LINE__);

	npca110 = devm_kzalloc(&i2c->dev, sizeof(struct npca110_priv),
			GFP_KERNEL);
	if (npca110 == NULL)
		return -ENOMEM;

	npca110->debounce_time = 200;
	npca110->linein_det_invert = 0;
	npca110->linein_inserted = false;

	npca110->npca110_i2c = i2c;
	i2c_set_clientdata(i2c, npca110);

	ret = snd_soc_register_codec(&i2c->dev,
			&soc_codec_dev_npca110, &npca110_dai, 1);
	if (ret != 0) {
		dev_err(&i2c->dev, "Failed to register CODEC: %d\n", ret);
		kfree(npca110);
		return ret;
	}

	npca110_reset_gpio = of_get_named_gpio_flags(np, "pwd-reset-gpio",
			0, &flags);
	if (npca110_reset_gpio < 0) {
		pr_err("%s Can not read property npca110 pwd-reset-gpio\n",
				__func__);
		npca110_reset_gpio = -1;
	} else {
		pr_info("npca110 pwd-reset-gpio = %d\n", npca110_reset_gpio);
		ret = gpio_request(npca110_reset_gpio, NULL);
		if (!ret) {
			pr_info("requset npca110-reset-gpio success!\n");
			//gpio_direction_output(53, 0);
			//msleep(30);
			gpio_direction_output(npca110_reset_gpio, 0);
			msleep(30);
			gpio_direction_output(npca110_reset_gpio, 1);
			msleep(30);
		} else {
			pr_err("requset npca110 pwd-con-gpio failed:%d\n", ret);
			return ret;
		}
	}

	npca110->gpio_det = of_get_named_gpio_flags(np, "gpio-det",
			0, &flags);
	if (npca110->gpio_det < 0) {
		pr_err("%s Can not read property npca110 gpio-det\n",
				__func__);
		npca110->gpio_det = -1;
	} else {
		pr_info("npca110 gpio-det = %d\n", npca110->gpio_det);
		INIT_DELAYED_WORK(&npca110->work, linein_work);
		npca110->linein_det_invert = !!(flags & OF_GPIO_ACTIVE_LOW);
		ret = devm_gpio_request_one(&i2c->dev, npca110->gpio_det,
				GPIOF_IN, "linein det");
		if (ret < 0)
			return ret;
		linein_irq = gpio_to_irq(npca110->gpio_det);
		ret = devm_request_threaded_irq(&i2c->dev, linein_irq, NULL,
				npca110_irq_handler,
				IRQF_TRIGGER_FALLING |
				IRQF_TRIGGER_RISING |
				IRQF_ONESHOT | IRQF_NO_SUSPEND,
				"npca110_interrupt", npca110);
		if (ret < 0) {
			dev_err(&i2c->dev, "request_irq failed: %d\n", ret);
			return ret;
		}

		enable_irq_wake(linein_irq);

		schedule_delayed_work(&npca110->work, msecs_to_jiffies(3000));
	}

	return 0;
}

static int npca110_i2c_remove(struct i2c_client *client)
{
	snd_soc_unregister_codec(&client->dev);
	pr_info("### %s,%d\n",__func__,__LINE__);

	return 0;
}

